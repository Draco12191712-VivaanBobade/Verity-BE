function lookupMoreKnowledge3(topic) {
  const key = topic.toLowerCase().trim();
  if (MORE_KNOWLEDGE_3[key]) return MORE_KNOWLEDGE_3[key];
  if (key.endsWith('s')) {
    const singular = key.slice(0, -1);
    if (MORE_KNOWLEDGE_3[singular]) return MORE_KNOWLEDGE_3[singular];
  }
  if (key.startsWith('the ')) {
    const withoutThe = key.slice(4);
    if (MORE_KNOWLEDGE_3[withoutThe]) return MORE_KNOWLEDGE_3[withoutThe];
  }
  return null;
}

